// Build-time only. Runtime uses the small, checked-in crop; never calls NASA.
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import {createRequire} from 'node:module';
import path from 'node:path';
const base='https://pds-geosciences.wustl.edu/mgs/mgs-m-mola-5-megdr-l3-v1/mgsl_300x/meg016/';
const dir=new URL('../outputs/mola/',import.meta.url);
await fs.mkdir(dir,{recursive:true});
async function source(name){
 const path=new URL(name,dir);
 try{return await fs.readFile(path);}catch{
  const response=await fetch(base+name);
  if(!response.ok)throw new Error(`NASA PDS ${response.status}`);
  const bytes=Buffer.from(await response.arrayBuffer());await fs.writeFile(path,bytes);return bytes;
 }
}
const label=(await source('megt90n000eb.lbl')).toString();
const input=await source('megt90n000eb.img');
if(input.length!==5760*2880*2 || !label.includes('MSB_INTEGER') || !label.includes('MAP_RESOLUTION               = 16.0'))throw new Error('Unexpected PDS product');
const bounds={west:54.025971997619806,east:215.92050022770937,south:-46.99448312479932,north:75.17348334633235};
const width=513,height=385,quantum=16;
const output=Buffer.alloc(width*height*2);
function elevation(lon,lat){
 // Pixel centres: 0.03125 E, 89.96875 N. Signed, big-endian metres above areoid.
 const x=lon*16-.5,y=(90-lat)*16-.5,ix=Math.floor(x),iy=Math.floor(y),u=x-ix,v=y-iy;
 const at=(dx,dy)=>input.readInt16BE(((iy+dy)*5760+ix+dx)*2);
 return (at(0,0)*(1-u)+at(1,0)*u)*(1-v)+(at(0,1)*(1-u)+at(1,1)*u)*v;
}
for(let y=0;y<height;y++)for(let x=0;x<width;x++){
 const h=elevation(bounds.west+x/(width-1)*(bounds.east-bounds.west),bounds.north-y/(height-1)*(bounds.north-bounds.south));
 // Horizontal delta coding improves gzip without a runtime decompressor dependency.
 const value=Math.round(h/quantum);
 const previous=x?Math.round(elevation(bounds.west+(x-1)/(width-1)*(bounds.east-bounds.west),bounds.north-y/(height-1)*(bounds.north-bounds.south))/quantum):0;
 output.writeInt16LE(value-previous,(y*width+x)*2);
}
const metadata={...bounds,width,height,quantum,source:base+'megt90n000eb.img',label:base+'megt90n000eb.lbl',dataset:'MGS-M-MOLA-5-MEGDR-L3-V1.0',sha256:createHash('sha256').update(input).digest('hex')};
const text=`// Generated by scripts/prepare-mars-region.mjs. NASA MGS/MOLA numerical elevation, not imagery.\nexport const MOLA_REGION = ${JSON.stringify(metadata,null,2)} as const;\nexport const MOLA_DELTA_BASE64 = ${JSON.stringify(output.toString('base64'))};\n`;
await fs.writeFile(new URL('../content/marsMolaData.ts',import.meta.url),text);
console.log(`MOLA crop ${width} × ${height}: ${gzipSync(text).length} gzip bytes; source SHA256 ${metadata.sha256}`);
// Original shaded-relief colour treatment, derived from the numerical crop.
const require=createRequire(import.meta.url);
const sharpDirectory=(await fs.readdir('node_modules/.pnpm')).find(name=>name.startsWith('sharp@'));
const sharp=require(path.resolve('node_modules/.pnpm',sharpDirectory,'node_modules/sharp'));
const rgb=Buffer.alloc(width*height*3),grid=new Float32Array(width*height);
for(let row=0;row<height;row++)for(let col=0,value=0;col<width;col++){
 const i=row*width+col;value+=output.readInt16LE(i*2);grid[i]=value*quantum;
}
for(let y=0;y<height;y++)for(let x=0;x<width;x++){
 const i=y*width+x,h=grid[i],dx=(h-grid[y*width+Math.max(0,x-1)])/800,dz=(h-grid[Math.max(0,y-1)*width+x])/800;
 const shade=Math.max(.4,Math.min(1.5,.92+dx*.4+dz*.5));
 rgb[i*3]=Math.max(0,Math.min(255,(137+h*.002)*shade));rgb[i*3+1]=Math.max(0,Math.min(255,(91+h*.0015)*shade));rgb[i*3+2]=Math.max(0,Math.min(255,(66+h*.001)*shade));
}
const overview=await sharp(rgb,{raw:{width,height,channels:3}}).webp({quality:65}).toBuffer();
await fs.writeFile(new URL('../public/art/mars-mola-overview.webp',import.meta.url),overview);
console.log(`Local minimap relief WebP: ${overview.length} bytes`);
